#!/usr/bin/env python3
"""Extract the AmiSSL 5.23 VBCC TLS bindings used by the native client.

Avoid compiling thousands of unused OpenSSL stack wrappers on a 68k.
No library offsets or constants are invented: declarations and macros are
copied from the pinned SDK. The ordinary SDK still supplies types and tags.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
NAMES = '''SSL_CTX_new TLS_client_method SSL_CTX_set_default_verify_paths
SSL_CTX_ctrl SSL_CTX_set_verify SSL_new SSL_set1_host SSL_ctrl SSL_set_fd
SSL_connect SSL_get_verify_result X509_verify_cert_error_string SSL_write
SSL_read SSL_get_error SSL_free SSL_CTX_free'''.split()
CONSTANTS = '''TLS1_2_VERSION SSL_VERIFY_PEER SSL_ERROR_ZERO_RETURN
SSL_ERROR_WANT_READ SSL_ERROR_WANT_WRITE SSL_CTRL_SET_MIN_PROTO_VERSION
SSL_CTRL_SET_TLSEXT_HOSTNAME TLSEXT_NAMETYPE_host_name'''.split()


def generate(include):
    bindings = (include / 'inline/amissl_protos.h').read_text()
    headers = '\n'.join((include / 'openssl' / name).read_text() for name in
                         ('types.h', 'ssl.h', 'tls1.h', 'prov_ssl.h'))
    license_header = (include / 'proto/amissl.h').read_text()
    license_header = license_header[license_header.index('/*'):license_header.index('*/') + 2]
    output = ['/* Generated by scripts/amiga/generate_amissl_subset.py from AmiSSL 5.23. */',
              license_header, '#ifndef TERMIC_AMISSL_TLS_VBCC_H',
              '#define TERMIC_AMISSL_TLS_VBCC_H', '#include <exec/types.h>',
              '#include <amissl/tags.h>',
              'extern struct Library *AmiSSLBase;',
              '/* OpenSSL Project Authors, Copyright 2001-2025. Apache-2.0. */']
    for name in ('SSL', 'SSL_CTX', 'SSL_METHOD', 'X509_STORE_CTX'):
        output.append(re.search(r'^typedef struct [a-z0-9_]+ ' + name + ';', headers, re.M).group())
    for name in CONSTANTS:
        output.append(re.search(r'^#\s*define ' + name + r'\s+[^\n]+', headers, re.M).group())
    for name in NAMES:
        declaration = re.search(r'^[^\n]* __' + name + r'\([^\n]+\n#define ' + name + r'\([^\n]+', bindings, re.M)
        if not declaration:
            raise ValueError('Missing binding: ' + name)
        output.append(declaration.group())
    for name in ('SSL_CTX_set_min_proto_version', 'SSL_set_tlsext_host_name'):
        macro = re.search(r'^#\s*define ' + name + r'\([^\n]*(?:\n[^\n]*)?', headers, re.M).group()
        # Take continuation lines exactly as supplied by the SDK.
        start = headers.index(macro)
        lines = headers[start:].splitlines()
        block = [lines.pop(0)]
        while block[-1].endswith('\\'):
            block.append(lines.pop(0))
        output.append('\n'.join(block))
    return '\n\n'.join(output) + '\n\n#endif\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('sdk', type=Path, help='AmiSSL Developer/include directory')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'amiga/native/vendor/amissl_tls_vbcc.h'
    content = generate(args.sdk)
    if args.check:
        if destination.read_text() != content:
            raise ValueError('Committed binding does not match the SDK')
    else:
        destination.write_text(content)

if __name__ == '__main__':
    main()
